/**
 * List tools exposed by Rapido RH MCP and refresh src/config/rhMcpToolMap.ts.
 *
 * Usage:
 *   RH_USER_ID=<supabase-uuid> npm run list-rh-tools
 *   RAPIDORH_ACCESS_TOKEN=<token> npm run list-rh-tools
 *
 * After Connect Rapido RH in Settings → Integrations, use RH_USER_ID.
 */

import { config } from "dotenv";
import * as fs from "fs";
import * as path from "path";

// Always load openclaw-server/.env regardless of cwd
config({ path: path.join(__dirname, "..", ".env") });

import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { connectionsStore } from "../src/integrations/ConnectionsStore";

function resolveUserId(): string | undefined {
  return (
    process.env.RH_USER_ID?.trim() ||
    process.env.CMS_USER_ID?.trim() ||
    process.env.CRM_USER_ID?.trim() ||
    process.env.BYPASS_USER_ID?.trim() ||
    undefined
  );
}

async function resolveAuth(): Promise<{ accessToken: string; mcpUrl: string }> {
  const manualToken = process.env.RAPIDORH_ACCESS_TOKEN?.trim();
  const mcpUrl =
    process.env.RAPIDORH_MCP_URL?.trim() || "https://rh.rapidosoftware.com/mcp";

  if (manualToken) {
    return { accessToken: manualToken, mcpUrl };
  }

  const userId = resolveUserId();
  if (!userId) {
    throw new Error(
      "Set RH_USER_ID in .env (your Supabase user UUID) or RAPIDORH_ACCESS_TOKEN.\n" +
        "Falls back to CMS_USER_ID / CRM_USER_ID if set.\n\n" +
        "Rapido RH must be connected first. With the server running:\n" +
        "  $uid = (Get-Content .env | Where-Object { $_ -match '^RH_USER_ID=' }) -replace '^RH_USER_ID=',''\n" +
        "  $r = Invoke-RestMethod \"http://127.0.0.1:3000/auth/rh/connect?format=json\" `\n" +
        "    -Headers @{ Accept=\"application/json\"; \"x-bypass-user-id\"=$uid }\n" +
        "  Start-Process $r.authUrl\n" +
        "Finish login in the browser, then re-run: npm run list-rh-tools"
    );
  }

  console.log(`Using user id ${userId.slice(0, 8)}… for Rapido RH connection lookup`);
  const conn = await connectionsStore.getRHConnection(userId);
  return { accessToken: conn.accessToken, mcpUrl: conn.mcpUrl };
}

function toInternalName(mcpName: string): string {
  const snake = mcpName.replace(/-/g, "_");
  return snake.startsWith("rh_") ? snake : `rh_${snake}`;
}

function writeToolMap(
  tools: Array<{ name: string; description?: string; inputSchema?: unknown }>
): void {
  const entries = tools
    .map((t) => {
      const internal = toInternalName(t.name);
      return `  ${internal}: "${t.name}",`;
    })
    .join("\n");

  const paramHints = tools
    .map((t) => {
      const props =
        t.inputSchema &&
        typeof t.inputSchema === "object" &&
        "properties" in (t.inputSchema as object)
          ? Object.keys(
              ((t.inputSchema as { properties?: Record<string, unknown> }).properties ??
                {}) as Record<string, unknown>
            )
          : [];
      const desc = (t.description || "").replace(/\*\//g, "* /").slice(0, 120);
      return ` * - ${t.name}${desc ? `: ${desc}` : ""}${
        props.length ? ` [${props.join(", ")}]` : ""
      }`;
    })
    .join("\n");

  const contents = `/**
 * Maps RapidoMeet internal RH tool ids (rh_*) to Rapido RH MCP tool names.
 * Auto-generated by \`npm run list-rh-tools\` — re-run after RH MCP changes.
 *
 * Discovered tools (${tools.length}):
${paramHints}
 */

/** Internal RapidoMeet id → Rapido RH MCP tool name (snake_case) */
export const RH_MCP_TOOL_NAMES: Record<string, string> = {
${entries}
};

export function resolveRhMcpToolName(internalTool: string): string {
  if (RH_MCP_TOOL_NAMES[internalTool]) return RH_MCP_TOOL_NAMES[internalTool];
  if (internalTool.startsWith("rh_")) return internalTool.slice(3);
  return internalTool;
}

export function isMappedRhTool(tool: string): boolean {
  return tool in RH_MCP_TOOL_NAMES || Object.values(RH_MCP_TOOL_NAMES).includes(tool);
}

/**
 * Strip orchestrator fields and shape args for Rapido RH MCP schemas.
 */
export function mapRhMcpArguments(
  _internalTool: string,
  params: Record<string, unknown>
): Record<string, unknown> {
  const args: Record<string, unknown> = { ...params };

  delete args.userId;
  delete args.sessionId;
  delete args._rh_route;

  if (args.data && typeof args.data === "object" && !Array.isArray(args.data)) {
    const nested = args.data as Record<string, unknown>;
    delete args.data;
    Object.assign(args, nested);
  }

  if (args.title != null && args.titre == null) args.titre = args.title;
  if (args.name != null && args.nom == null) args.nom = args.name;
  if (args.first_name != null && args.prenom == null) args.prenom = args.first_name;
  if (args.last_name != null && args.nom == null) args.nom = args.last_name;
  if (args.firstname != null && args.prenom == null) args.prenom = args.firstname;
  if (args.lastname != null && args.nom == null) args.nom = args.lastname;

  return args;
}
`;

  const outPath = path.join(__dirname, "..", "src", "config", "rhMcpToolMap.ts");
  fs.writeFileSync(outPath, contents, "utf8");
  console.log(`\nWrote ${outPath}`);

  const snapshotPath = path.join(__dirname, "..", "src", "config", "rhMcpTools.snapshot.json");
  fs.writeFileSync(
    snapshotPath,
    JSON.stringify(
      tools.map((t) => ({
        name: t.name,
        description: t.description ?? null,
        params: t.inputSchema
          ? Object.keys(
              ((t.inputSchema as { properties?: Record<string, unknown> }).properties ??
                {}) as Record<string, unknown>
            )
          : [],
      })),
      null,
      2
    ),
    "utf8"
  );
  console.log(`Wrote ${snapshotPath}`);
}

async function main() {
  const { accessToken, mcpUrl } = await resolveAuth();

  console.log(`Connecting to ${mcpUrl} ...\n`);

  const transport = new StreamableHTTPClientTransport(new URL(mcpUrl), {
    requestInit: {
      headers: { Authorization: `Bearer ${accessToken}` },
    },
  });

  const client = new Client(
    { name: "RapidoMeetRhToolLister", version: "1.0.0" },
    { capabilities: {} }
  );

  await client.connect(transport);

  const { tools } = await client.listTools();

  if (!tools.length) {
    console.log("No tools returned.");
    await client.close();
    return;
  }

  console.log(`Found ${tools.length} tool(s):\n`);

  for (const tool of tools) {
    console.log(`• ${tool.name}`);
    if (tool.description) {
      console.log(`  ${tool.description}`);
    }
    if (tool.inputSchema) {
      const props = (tool.inputSchema as { properties?: Record<string, unknown> }).properties;
      if (props) {
        console.log(`  params: ${Object.keys(props).join(", ") || "(none)"}`);
      }
    }
    console.log();
  }

  console.log("--- tool names only ---");
  console.log(tools.map((t) => t.name).join("\n"));

  writeToolMap(tools);

  await client.close();
}

main().catch((err) => {
  console.error("Failed:", (err as Error).message);
  process.exit(1);
});
